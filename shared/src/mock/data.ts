const HOUR = 3_600_000;
const DAY = 24 * HOUR;
const now = Date.now();

/** `h` hours ago. Keeps the 24-hour counters populated. */
const ago = (h: number) => new Date(now - h * HOUR).toISOString();

const bgy = (name: string) => SJDM_BARANGAYS.find((b) => b.name === name)!;

/** Offset from a barangay centre so map pins do not stack. */
const near = (name: string, dLat: number, dLng: number) => ({
  latitude: bgy(name).center.latitude + dLat,
  longitude: bgy(name).center.longitude + dLng,
});

const photo = (kind: 'dog' | 'cat' | 'other', lock: number) =>
  `https://loremflickr.com/640/480/${kind === 'other' ? 'pet' : kind}?lock=${lock}`;

